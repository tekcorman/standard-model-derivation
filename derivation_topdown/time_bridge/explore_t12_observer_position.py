# Build the learner explicitly.  The observer at position beta reads the substrate THROUGH the state
# rho_beta (it samples band energies with the Gibbs weights p_i = rho_beta).  Reading is an
# accumulate-then-update step.  A SELF-CONSISTENT position is a fixed point: the position the
