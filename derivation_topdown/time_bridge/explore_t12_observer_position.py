# Self-funding NET(beta) = I(beta) - Cost(beta).  We look for a distinguished zero/extremum.
def logZ(beta):
    w = -beta*e; m = w.max(); return m + np.log(np.sum(np.exp(w-m)))   # log sum exp(-beta e)
def I_gain(beta):    # information gained vs the hot uniform state = D_KL(rho_beta || uniform)
    p = rho_beta(beta); u = np.ones_like(p)/len(p)
