#
# Concretely (a conjugate / EM-style self-consistency): the observer estimates the "temperature" of
# the run from what it sees.  If it reads energies with weights rho_beta, the MAXIMUM-LIKELIHOOD /
# moment estimate of the inverse temperature beta_hat that BEST explains the observed mean energy is a
