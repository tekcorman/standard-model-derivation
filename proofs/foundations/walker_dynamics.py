def reduce_word(word):
    """
    Reduce a word in F_inv(E) by cancelling adjacent identical symbols.
    Stack-based; order-independent for free involutive monoids
    (Serre 1980 §I.1 Proposition 4).
    """
    stack = []
    for e in word:
        if stack and stack[-1] == e:
            stack.pop()
        else:
            stack.append(e)
    return stack


