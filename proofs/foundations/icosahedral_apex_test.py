def enumerate_group(generators, dim, max_order=200, tol=1e-6):
    """Enumerate the finite subgroup of U(dim) generated by `generators`.
    Uses BFS closure with deduplication by Frobenius distance.
    Returns list of group elements (matrices)."""
    I = np.eye(dim, dtype=complex)
    elements = [I.copy()]

    def member_idx(g, els):
        for i, e in enumerate(els):
            if la.norm(g - e) < tol:
                return i
        return -1

    queue = list(generators) + [g.conj().T for g in generators]
    while queue and len(elements) <= max_order:
        # Try adding new element: g_new = g_existing @ g_queue
        new_elements_added = False
        for h in queue:
            for g in elements[:]:
                g_new = g @ h
                if member_idx(g_new, elements) < 0:
                    elements.append(g_new)
                    new_elements_added = True
                    if len(elements) > max_order:
                        return elements
        if not new_elements_added:
            break
    return elements


def element_order(g, max_order=20, tol=1e-6):
    """Return the smallest positive integer n such that g^n = I."""
    I = np.eye(g.shape[0], dtype=complex)
    g_pow = g.copy()
    for n in range(1, max_order + 1):
        if la.norm(g_pow - I) < tol:
            return n
        g_pow = g_pow @ g
    return -1


