def conjugacy_classes_by_trace(elements, tol=1e-4):
    """Cluster elements by (order, trace) — for 2I this fully separates the
    9 conjugacy classes."""
    keys = []
    for g in elements:
        ord_g = element_order(g)
        tr = complex(np.trace(g))
        # Round trace to clustering precision
        key = (ord_g, round(tr.real, 3), round(tr.imag, 3))
        keys.append(key)
    classes = defaultdict(list)
    for i, k in enumerate(keys):
        classes[k].append(i)
    return dict(classes)


