# Build B3 gamma matrices (copied from theorem_B3_spinor_fermion.py for
# self-containment; identical conventions).
I2 = np.eye(2, dtype=complex)
sx = np.array([[0, 1], [1, 0]], dtype=complex)
sy = np.array([[0, -1j], [1j, 0]], dtype=complex)
sz = np.array([[1, 0], [0, -1]], dtype=complex)


def kron(*mats):
    out = mats[0]
    for m in mats[1:]:
        out = np.kron(out, m)
    return out


Gamma = [None] * 7
Gamma[1] = kron(sx, I2, I2)
Gamma[2] = kron(sy, I2, I2)
Gamma[3] = kron(sz, sx, I2)
Gamma[4] = kron(sz, sy, I2)
Gamma[5] = kron(sz, sz, sx)
Gamma[6] = kron(sz, sz, sy)
I8 = np.eye(8, dtype=complex)

# Verify Clifford relations (B3 cross-check).
for i, j in itertools.product(range(1, 7), repeat=2):
    lhs = Gamma[i] @ Gamma[j] + Gamma[j] @ Gamma[i]
    rhs = 2.0 * (1.0 if i == j else 0.0) * I8
    assert np.allclose(lhs, rhs, atol=TOL)

# Chirality.
G7 = -1j * Gamma[1] @ Gamma[2] @ Gamma[3] @ Gamma[4] @ Gamma[5] @ Gamma[6]

# Build U_C3 on the 8-dim spinor. The C_3 on V_6 acts as P_so6 (orthogonal).
# Its lift to Spin(6) is the Spin element whose adjoint action on V_6 is P_so6.
# We build it by exponentiating the Lie-algebra logarithm of P_so6 in so(6),
# and then exponentiating the corresponding element of spin(6) (using bivectors).

# log(P_so6) is a real antisymmetric 6x6 matrix L_so6 with P_so6 = exp(L_so6).
# Compute via complex log of eigenvalues; pair conjugate eigenvalues.
evals_so6, evecs_so6 = np.linalg.eig(P_so6)
# In real form, P_so6 is block-diagonal in 2x2 rotation blocks (real basis
# pairs from the complex-conjugate eigenvalue pairs) plus a 2-dim trivial
# invariant subspace (the two +1 eigenvectors).
# Compute the matrix logarithm via scipy-free approach: project onto the
# eigenbasis and take principal log of each eigenvalue.
log_evals = np.array([np.log(ev) for ev in evals_so6])  # complex log
# Reconstruct log(P_so6) in original basis.
L_so6 = (evecs_so6 @ np.diag(log_evals) @ np.linalg.inv(evecs_so6))
# Should be antisymmetric (purely imaginary in real eigenbasis); discard
# tiny imag part.
L_so6_real = L_so6.real
# Verify exp(L_so6_real) ~ P_so6.
from scipy.linalg import expm
assert np.allclose(expm(L_so6_real), P_so6, atol=1e-10), \
    "L_so6 does not exponentiate to P_so6"
# Verify antisymmetry.
assert np.allclose(L_so6_real, -L_so6_real.T, atol=1e-10), \
    "L_so6 not antisymmetric (should be in so(6))"

# Build the spin lift: an element of spin(6) corresponding to L_so6 via
# the Lie algebra isomorphism so(6) <-> {antisymmetric bivector elements}.
# Standard formula: for so(6) element L with L_{ab}, the spin generator is
#     X_spin = (1/4) sum_{a<b} L_{ab} (Gamma_a Gamma_b - Gamma_b Gamma_a)
#            = (1/2) sum_{a<b} L_{ab} Gamma_{ab}
# where Gamma_{ab} = (1/2)[Gamma_a, Gamma_b].

def biv(a, b):
    return 0.5 * (Gamma[a] @ Gamma[b] - Gamma[b] @ Gamma[a])


X_spin = np.zeros((8, 8), dtype=complex)
for i in range(6):
    for j in range(i + 1, 6):
        X_spin += L_so6_real[i, j] * biv(i + 1, j + 1)
# Note: the 1/2 vs 1/4 normalization depends on convention; we want
# exp(X_spin) to act on V_6 as P_so6 via the adjoint. Using
# Gamma_{ab} as the spin generator (already antihermitian times i)
# and L_{ab} antisymmetric, the conventional formula is X_spin =
# (1/2) Sum_{a<b} L_{ab} Gamma_{ab}.

X_spin_half = 0.5 * X_spin
U_C3_S = expm(X_spin_half)

# Verify U_C3_S has order 3 (up to a sign — Spin double cover may give
# U^3 = +I or -I).
U3 = U_C3_S @ U_C3_S @ U_C3_S
print(f"  ||U_C3_S^3 - I||  = {np.linalg.norm(U3 - I8):.3e}")
print(f"  ||U_C3_S^3 + I||  = {np.linalg.norm(U3 + I8):.3e}")
assert (np.allclose(U3, I8, atol=1e-9) or np.allclose(U3, -I8, atol=1e-9)), \
    "U_C3_S^3 should be ±I (Spin double cover)"

# If U^3 = -I, multiply by a cube root of -1 to make U^3 = +I (lift choice).
if np.allclose(U3, -I8, atol=1e-9):
    U_C3_S = np.exp(1j * np.pi / 3) * U_C3_S
    U3 = U_C3_S @ U_C3_S @ U_C3_S
    assert np.allclose(U3, I8, atol=1e-9), "After phase correction, U^3 != I"
print(f"  After lift choice: ||U_C3_S^3 - I||  = "
      f"{np.linalg.norm(U_C3_S @ U_C3_S @ U_C3_S - I8):.3e}")

# Verify [U_C3_S, Gamma_7] = 0 (chirality preserved by SO(6) -> spin lift).
comm_chir = U_C3_S @ G7 - G7 @ U_C3_S
print(f"  ||[U_C3_S, Gamma_7]||  = {np.linalg.norm(comm_chir):.3e}  (should be 0)")
assert np.linalg.norm(comm_chir) < 1e-9, "U_C3_S should commute with Gamma_7"

# Compute isotypic dimensions on S by diagonalising U_C3_S.
evals_S = np.linalg.eigvals(U_C3_S)
print(f"  Eigenvalues of U_C3_S on S (sorted by arg):")
for ev in sorted(evals_S, key=lambda x: np.angle(x)):
    print(f"    {ev:+.6f}  (arg = {np.angle(ev):+.4f})")

