# Verify it's a permutation and order 3.
assert set(edge_perm.values()) == set(K4_EDGES), "C_3 not bijection on edges"
edge_perm3 = {e: apply_sigma_to_edge(apply_sigma_to_edge(apply_sigma_to_edge(e)))
              for e in K4_EDGES}
assert edge_perm3 == {e: e for e in K4_EDGES}, "edge permutation order != 3"

# Find orbit structure.
visited = set()
orbits = []
for e in K4_EDGES:
    if e in visited:
        continue
    orbit = [e]
    cur = apply_sigma_to_edge(e)
    while cur != e:
        orbit.append(cur)
        cur = apply_sigma_to_edge(cur)
