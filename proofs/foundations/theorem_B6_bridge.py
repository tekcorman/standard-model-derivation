# C_3 vertex permutation from B5.3-core: sigma = (v_0)(v_1 v_3 v_2).
# I.e. sigma(0)=0, sigma(1)=3, sigma(2)=1, sigma(3)=2.
SIGMA = {0: 0, 1: 3, 2: 1, 3: 2}


def apply_sigma_to_edge(edge):
    a, b = edge
    new = (SIGMA[a], SIGMA[b])
    return tuple(sorted(new))


# Verify sigma^3 = id on K_4 vertices and edges.
sigma3 = {v: SIGMA[SIGMA[SIGMA[v]]] for v in K4_VERTICES}
assert sigma3 == {v: v for v in K4_VERTICES}, "sigma^3 != id on vertices"

# C_3 permutation on the 6 K_4 edges.
