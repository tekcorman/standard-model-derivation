def main():
    print("=" * 76)
    print("Path B — chiral Z_2 J at N_1 induces (T_0 T_2) on V_Ram U_T readings")
    print("=" * 76)

    bonds = find_bonds()
    directed = build_directed_edges(bonds)
    n = len(directed)
    assert n == 12

    B = bloch_hashimoto(N1, directed)

    # ------------------------------------------------------------------
    # C1: tr(B(k)^L) = 0 for odd L at N_1 (and other N-points), non-zero
    #     at Γ and generic k. This is the structural source of J.
    # ------------------------------------------------------------------
    print("\n[C1] Spectral negation source: tr(B(k)^L) for L = 1..6")
    print(f"     {'k':>22}  {'L=1':>10} {'L=2':>10} {'L=3':>10}"
          f" {'L=4':>10} {'L=5':>10} {'L=6':>10}")
    sample_k = [
        ("Γ = (0,0,0)",         np.array([0.0, 0.0, 0.0])),
        ("N_1 = (0,0,1/2)",     N1),
        ("N_2 = (1/2,0,0)",     np.array([0.5, 0.0, 0.0])),
        ("N_3 = (0,1/2,0)",     np.array([0.0, 0.5, 0.0])),
        ("H = (1/2,1/2,1/2)",   np.array([0.5, 0.5, 0.5])),
        ("rand1",               np.array([0.13, 0.27, 0.41])),
    ]
    for label, k in sample_k:
        Bk = bloch_hashimoto(k, directed)
        trs = [abs(np.trace(np.linalg.matrix_power(Bk, L))) for L in range(1, 7)]
        line = f"     {label:>22}  " + " ".join(f"{t:>9.2e}" for t in trs)
        print(line)
    # N_1 odd-L vanishing
    for L in (1, 3, 5):
        tr = np.trace(np.linalg.matrix_power(B, L))
        assert abs(tr) < 1e-10, f"tr(B(N_1)^{L}) = {tr} (expected 0)"
    print("     ✓ tr(B(N_1)^L) = 0 for L = 1, 3, 5 (machine precision)")
    print("     ✓ Non-zero at Γ for L = 3, 6 → spectral negation is N-point-specific")

    eigs, V = la.eig(B)
    ram_idx = sorted(
        [i for i in range(n) if abs(abs(eigs[i]) ** 2 - H_MOD_SQ_RAM) < 1e-6],
        key=lambda i: (eigs[i].real, eigs[i].imag),
    )
    assert len(ram_idx) == 8

    # ------------------------------------------------------------------
    # C2: Negation pairing within V_Ram
    # ------------------------------------------------------------------
    print("\n[C2] Negation pairing on V_Ram: each λ has unique partner -λ in V_Ram")
    ram_eigs = [eigs[i] for i in ram_idx]
    pair = [None] * 8
    for i in range(8):
        for j in range(8):
            if i != j and abs(ram_eigs[i] + ram_eigs[j]) < 1e-6:
                pair[i] = j
                break
        assert pair[i] is not None, f"no -λ partner for ram[{i}]"
    print(f"     pairing (i ↔ pair(i)):")
    for i in range(8):
        print(f"       ram[{i}] (λ = {ram_eigs[i]:+.4f}) ↔ "
              f"ram[{pair[i]}] (λ = {ram_eigs[pair[i]]:+.4f})")
    # Involutive
    for i in range(8):
        assert pair[pair[i]] == i

    # ------------------------------------------------------------------
    # C3: Construct J on V_Ram via spectral negation pairing.
    # J is well-defined up to per-eigenvalue phase choices. We use
    # the canonical right-eigenvector / biorthogonal-dual choice to
    # ensure J B J^{-1} = -B exactly on V_Ram.
    # ------------------------------------------------------------------
    print("\n[C3] J on V_Ram: J ψ_λ = ψ_{-λ}  ⇒  J B J^{-1} = -B")
    Vinv = la.inv(V)
    V_ram = V[:, ram_idx]                        # 12x8 right eigenvectors (raw)
    W_ram = Vinv[ram_idx, :].conj().T             # 12x8 left eigenvectors
    biortho = W_ram.conj().T @ V_ram
    print(f"     biorthogonality ||W^† V - I|| = {la.norm(biortho - np.eye(8)):.2e}")
    assert la.norm(biortho - np.eye(8)) < 1e-9

    # J = Σ_i v_{pair(i)} ⟨w_i|, restricted to V_ram subspace
    J = np.zeros((n, n), dtype=complex)
    for i in range(8):
        J += np.outer(V_ram[:, pair[i]], W_ram[:, i].conj())

    # Verify: J B v_i = -B J v_i (on V_ram)
    err = la.norm(J @ B @ V_ram - (-B) @ J @ V_ram)
    print(f"     ||J B v_i - (-B J v_i)|| on V_ram = {err:.2e}")
    assert err < 1e-9

    # ------------------------------------------------------------------
    # C4: Diagonal expectation transformation
    # ------------------------------------------------------------------
    print("\n[C4] Diagonal expectation transformation under J: λ → -λ")
    P0 = projector_T(T_PAIRS[0], directed)
    P1 = projector_T(T_PAIRS[1], directed)
    P2 = projector_T(T_PAIRS[2], directed)
    B3 = B @ B @ B
    U0 = P0 @ B3 @ P0
    U1 = P1 @ B3 @ P1
    U2 = P2 @ B3 @ P2

    print("     Predicted:")
    print("       ⟨ψ_{-λ}|U_{T_0}|ψ_{-λ}⟩ = -⟨ψ_λ|U_{T_2}|ψ_λ⟩")
    print("       ⟨ψ_{-λ}|U_{T_2}|ψ_{-λ}⟩ = -⟨ψ_λ|U_{T_0}|ψ_λ⟩")
    print("       ⟨ψ_{-λ}|U_{T_1}|ψ_{-λ}⟩ = -⟨ψ_λ|U_{T_2}|ψ_λ⟩  (by item-1 σ)")
    print()
    print(f"     {'i':>3} {'λ':>20} {'⟨U_T0⟩(-λ) + ⟨U_T2⟩(λ)':>28}"
          f" {'⟨U_T2⟩(-λ) + ⟨U_T0⟩(λ)':>28} {'⟨U_T1⟩(-λ) + ⟨U_T2⟩(λ)':>28}")
    max_err = 0.0
    for i in range(8):
        psi = V[:, ram_idx[i]]
        psi_n = V[:, ram_idx[pair[i]]]
        nrm = np.real(psi.conj() @ psi)
        nrm_n = np.real(psi_n.conj() @ psi_n)
        r0 = (psi.conj() @ U0 @ psi) / nrm
        r2 = (psi.conj() @ U2 @ psi) / nrm
        r0_n = (psi_n.conj() @ U0 @ psi_n) / nrm_n
        r1_n = (psi_n.conj() @ U1 @ psi_n) / nrm_n
        r2_n = (psi_n.conj() @ U2 @ psi_n) / nrm_n
        d1 = abs(r0_n + r2)
        d2 = abs(r2_n + r0)
        d3 = abs(r1_n + r2)
        max_err = max(max_err, d1, d2, d3)
        print(f"     {i:>3} {ram_eigs[i]:>20.4f} {d1:>28.2e}"
              f" {d2:>28.2e} {d3:>28.2e}")
    print(f"     max deviation across 8 V_Ram modes = {max_err:.2e}  (must be 0) ✓")
    assert max_err < 1e-9

    # ------------------------------------------------------------------
    # C5: Sanity — ⟨(T_0 T_1), (T_0 T_2)⟩ = S_3 (matches parallel doc S_3)
    # ------------------------------------------------------------------
    print("\n[C5] Sanity: ⟨σ_T = (T_0 T_1), J_T = (T_0 T_2)⟩ generates S_3 on")
    print("     {T_0, T_1, T_2} (matches algebra-level S_3 of parallel doc)")

    def apply_perm(perm, x):
        """Apply permutation (as tuple of length 3) to triangle index x."""
        return perm[x]

    sigma_T = (1, 0, 2)        # (T_0 T_1)
    J_T = (2, 1, 0)            # (T_0 T_2)
    e_perm = (0, 1, 2)

    def compose(p, q):
        return tuple(p[q[i]] for i in range(3))

    # Generate the group
    group = {e_perm, sigma_T, J_T}
    changed = True
    while changed:
        changed = False
        for p in list(group):
            for q in list(group):
                pq = compose(p, q)
                if pq not in group:
                    group.add(pq)
                    changed = True
    print(f"     |⟨σ_T, J_T⟩| = {len(group)}    (must be 6 = |S_3|) ✓")
    assert len(group) == 6
    print(f"     elements:")
    for g in sorted(group):
        cycle_struct = "id" if g == e_perm else (
            "transp" if sum(1 for i in range(3) if g[i] != i) == 2 else "3-cycle"
        )
        print(f"       {g}  ({cycle_struct})")

    # Z_3 subgroup
    z3 = {e_perm}
    g = compose(sigma_T, J_T)
    z3.add(g)
    z3.add(compose(g, g))
    print(f"     Z_3 subgroup ⟨σ_T · J_T⟩ = {sorted(z3)}    (3-cycles + id)")
    assert len(z3) == 3

    # ------------------------------------------------------------------
    # C6: Z_3 ⊂ S_3 coincides with structural Z_3 (B6 C_3 = (1 2 3) on K_4 verts)
    # ------------------------------------------------------------------
