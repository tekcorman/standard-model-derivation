    # Summary
    # ------------------------------------------------------------------
    print()
    print("=" * 76)
    print("THEOREM (proven)")
    print("=" * 76)
    print()
    print("  At N_1, the within-V_Ram(N_1) chiral unitary J, built from the")
    print("  spectral negation pairing implied by tr(B(N_1)^L) = 0 for odd L,")
    print("  satisfies J B(N_1) J^{-1} = -B(N_1) on V_Ram(N_1). It induces")
