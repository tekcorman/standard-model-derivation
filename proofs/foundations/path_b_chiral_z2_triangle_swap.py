    # C7: Within-V_Ram(N_1) ↔ algebra-level distinction
    # ------------------------------------------------------------------
    print("\n[C7] Within-V_Ram(N_1) ↔ algebra-level (parallel doc) distinction")
    print("     The (T_0 T_2) triangle-index permutation arises from TWO")
    print("     different operators:")
    print()
